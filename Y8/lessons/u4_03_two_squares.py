import turtle

turtle.penup()
turtle.backward(150)
turtle.pendown()

for i in range(4):
    turtle.forward(100)
    turtle.right(90)

turtle.penup()
turtle.forward(150)
turtle.pendown()

for i in range(4):
    turtle.forward(100)
    turtle.right(90)

